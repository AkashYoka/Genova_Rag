"""CKEditor / sticky-notes HTML → professionally typeset document PDF."""
from __future__ import annotations

import re
from datetime import datetime
from typing import List, Optional

from reportlab.lib.units import mm
from reportlab.platypus import Flowable, HRFlowable, Paragraph, Spacer

from app.publishing.builder import (
    build_cover,
    build_toc,
    finalize_pdf,
    question_preview,
)
from app.publishing.design import BORDER, build_styles, content_width
from app.publishing.html_flow import extract_headings_from_html, html_to_flowables
from app.publishing.markdown import safe


def _infer_title(html: str, explicit: Optional[str] = None) -> str:
    if explicit and explicit.strip():
        return explicit.strip()
    headings = extract_headings_from_html(html)
    if headings:
        return headings[0][1]
    plain = re.sub(r"<[^>]+>", " ", html or "")
    plain = re.sub(r"\s+", " ", plain).strip()
    if plain:
        return question_preview(plain, 80)
    return "Untitled note"


def _infer_subtitle(html: str, title: str) -> str:
    headings = extract_headings_from_html(html)
    if len(headings) >= 2:
        return f"A Genova notes document with {len(headings)} sections"
    plain = re.sub(r"<[^>]+>", " ", html or "")
    plain = re.sub(r"\s+", " ", plain).strip()
    if plain and plain != title:
        return question_preview(plain, 140)
    return "Professionally typeset export from Genova Notes"


def format_notes_pdf(
    html: str,
    *,
    title: Optional[str] = None,
    note_id: Optional[str] = None,
) -> bytes:
    """Render CKEditor HTML as a premium editorial PDF (same design system as Chat)."""
    styles = build_styles()
    cw = content_width()

    doc_title = _infer_title(html, title)
    subtitle = _infer_subtitle(html, doc_title)

    plain = re.sub(r"<[^>]+>", " ", html or "")
    words = len(re.findall(r"\S+", plain))

    # Parse content first so TOC bookmarks match real destinations
    content_flows, heading_bookmarks = html_to_flowables(html, styles, cw)
    sections = len(heading_bookmarks)

    story: List[Flowable] = []
    story.extend(
        build_cover(
            styles,
            title=doc_title,
            subtitle=subtitle,
            kind_label="Document ebook",
            meta_lines=[
                f"<b>Sections</b>  {sections}" if sections else "<b>Sections</b>  —",
                f"<b>Word count</b>  ~{words}",
                f"<b>Export date</b>  {datetime.now().strftime('%Y-%m-%d %H:%M')}",
                f"<b>Source</b>  Genova Notes"
                + (f" · {safe(note_id)}" if note_id else ""),
            ],
        )
    )

    if sections >= 2:
        toc_entries = [
            (name, htitle, 0 if level <= 2 else 1)
            for name, htitle, level in heading_bookmarks
        ]
        story.extend(build_toc(styles, toc_entries, heading="Table of contents"))

    story.extend(content_flows)

    story.append(Spacer(1, 6 * mm))
    story.append(
        HRFlowable(
            width="100%",
            thickness=0.5,
            color=BORDER,
            spaceBefore=2 * mm,
            spaceAfter=3 * mm,
        )
    )
    story.append(
        Paragraph(
            f"Generated by Genova by Yoka · {datetime.now().strftime('%Y-%m-%d')} · "
            "Exported from Notes.",
            styles["footer_note"],
        )
    )

    return finalize_pdf(
        story,
        title=f"{doc_title} — Genova",
        subject="Genova notes document",
    )
